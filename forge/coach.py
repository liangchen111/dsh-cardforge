# 卡里的四段 —— **给 ElecKoi 里的 AI 在对话中做卡用**。
# 与规程共用同一份内容：「红线」两边本来就是同一段；
# 「总则 / 访谈 / 交付」只在卡里，因为规程的读者能跑命令、流程写在 §一，
# 而对话里的 AI 不建工程 —— 它要的是**怎么问、问到什么程度算够、交出去长什么样**。
对话段 = OrderedDict([
    ("总则", 卡总则),
    ("访谈", 卡访谈),
    ("交付", 卡交付),
    ("红线", 卡红线),
])


def _规程段():
    """把规程正文按 `## ` 切成 [(标题, 全文)]，标题不含前导 `## `。

    切的是**生成物本身**，不是手写的映射表 —— 「规程有几节」于是永远跟着文档走，
    不会出现「文档加了节、取节的地方还是老样子」这种不同步（第 29 项盯着的那类）。
    """
    段, 当前 = [], None
    for 行 in 规程正文().split("\n"):
        if 行.startswith("## "):
            if 当前:
                段.append(当前)
            当前 = [行[3:].strip(), [行]]
        elif 当前 is not None:
            当前[1].append(行)
    if 当前:
        段.append(当前)
    return [(t, "\n".join(ls).rstrip() + "\n") for t, ls in 段]


def _认名(名, 全部, 量词):
    """把一个松散的名字认成**唯一**一项。认不出、认重了都当场报清楚，绝不静默挑一个。

    三级匹配：先全等，再前缀，最后包含。写「三」能命中「三、开场白」，
    写「预算」能命中「预算 · 每句话都在跟聊天记录抢位置」；
    写「机制」会命中两篇 —— 这时**报出两个候选**让调用方写全，
    而不是随便挑一个（挑错了读者拿到的是另一篇，且毫无察觉）。
    """
    名 = (名 or "").strip()
    if not 名:
        raise KeyError("%s 没给。有这些：%s" % (量词, " / ".join(全部)))
    候选 = ([t for t in 全部 if t == 名] or
            [t for t in 全部 if t.startswith(名)] or
            [t for t in 全部 if 名 in t])
    if not 候选:
        raise KeyError("没有叫「%s」的%s。有这些：%s" % (名, 量词, " / ".join(全部)))
    if len(候选) > 1:
        raise KeyError("「%s」对上了不止一个%s：%s（写全一点）"
                       % (名, 量词, " / ".join(候选)))
    return 候选[0]


def 取节(名):
    """取规程的一节（例：`三` / `三、开场白` / `开场白`）。"""
    段 = dict(_规程段())
    标题 = _认名(名, list(段), "节")
    return 段[标题]


def 取篇(名):
    """取方法论的一篇（例：`预算` / `预算 · 每句话都在跟聊天记录抢位置`）。"""
    标题 = _认名(名, list(方法论), "篇")
    return "### %s\n\n%s\n" % (标题, 方法论[标题]["正文"])


def 取对话(名):
    """取「在对话里做卡」的四段之一（总则 / 访谈 / 交付 / 红线）。"""
    标题 = _认名(名, list(对话段), "段")
    return 对话段[标题] + "\n"


def 目录():
    """给 AI 的短目录 —— 先看它，再按需取一段。

    一份规程一万七千字，一次全塞进上下文既贵又冲淡重点。目录只有几十行：
    知道「有哪些节、有哪些篇、哪几篇是必读」就够决定该取哪一段了。
    """
    行 = ["# ElecKoi 制卡规程 · 目录",
          "",
          "取一段：`python forge.py guide --节 <名>` / `--篇 <名>` / `--对话 <名>`；全文：`--全文`。",
          "",
          "## 节（按顺序做）"]
    for 标题, _ in _规程段():
        行.append("  %s" % 标题)
    行 += ["", "## 篇（方法论 · 写内容之前先读「必读」的）"]
    for 标题, it in 方法论.items():
        行.append("  [%s] %s —— %s" % (it["档位"], 标题, it["提示"]))
    行 += ["", "## 对话段（在 ElecKoi 里对着玩家做卡时读：怎么问、怎么交）",
           "  [总则] 你是制卡师 —— 身份与边界（不许替玩家编设定）",
           "  [访谈] 一层一层问 —— 一次问什么、问到什么程度算够、什么时候给草稿",
           "  [交付] 你输出什么 —— 每定完一层交给玩家什么、怎么收尾",
           "  [红线] 会被静默吃掉的写法（与第九节同一段）"]
    return "\n".join(行)          # 末尾不加换行：调用处一律 print()，由它补


