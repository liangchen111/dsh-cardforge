# ============================================================ 出卡

def _空卡():
    """从骨架 spec 抄一份空壳：只留开场白条目，变量与正则清空。

    形状照抄是**故意的** —— 骨架是被 check 与自检盯着的合法形状，
    这里手拼字段迟早会拼出一张「看着对、其实少键」的卡。
    """
    d = M.yload(_骨架spec)
    d["character"]["name"] = 卡名
    lib = d["library"]
    开场 = [e for e in (lib.get("entries") or []) if e.get("kind") == "opening"]
    if not 开场:
        raise RuntimeError("骨架 spec 里没有开场白条目，不肯拿它当模板。")
    开场[0]["title"] = "AI角色开场白"
    开场[0]["content"] = 卡开场白
    # 开场白的「方案」留着骨架那份**原样不动**（id 与 default 指向是配对的，
    # 自己新造 id 会让默认方案指向一个不存在的方案 —— 这正是 OPENING-DEFAULT 那条错）。
    # 只把每个方案的正文换成我们的开场白。
    for msg in (开场[0].get("opening_messages") or []):
        if isinstance(msg, dict) and "content" in msg:
            msg["content"] = 卡开场白
    lib["entries"] = [开场[0]]
    lib["groups"] = []
    d["variables"] = {}
    d["regex_rules"] = []
    return d


def _认回身份(spec, 旧):
    """把上一版 spec 里同一条目／分组的 id 与时间戳认回来。

    动机（2026-10-15 实测）：`coach` 每次重生成都发新 uuid 与新时间戳 ⇒ 连跑两次
    产物字节不同；用户导过上一版再导新版，卡内 id 全变（ElecKoi 侧按 id 记的状态
    可能对不上）。**内容是新的，身份该是旧的。**
    配对键用「条目标题 / 分组名」：这两样是给人看的、也是规程里写死的东西；
    真新增的条目没有旧主，照旧用新 id。
    """
    新 = M.yload(spec)
    旧库 = (旧 or {}).get("library") or {}
    旧目, 旧组 = {}, {}
    for e in (旧库.get("entries") or []):
        if isinstance(e, dict) and e.get("title"):
            旧目.setdefault(str(e["title"]), e)
    for g in (旧库.get("groups") or []):
        if isinstance(g, dict) and g.get("name"):
            旧组.setdefault(str(g["name"]), g)

    新库 = 新.get("library") or {}
    组旧id = {}
    for g in (新库.get("groups") or []):
        老 = 旧组.get(str(g.get("name")))
        if not 老:
            continue
        组旧id[str(g.get("id"))] = 老.get("id")
        g["id"] = 老.get("id") or g.get("id")
        g["created_at"] = 老.get("created_at") or g.get("created_at")
        g["updated_at"] = 老.get("updated_at") or g.get("updated_at")
    认回 = 0
    for e in (新库.get("entries") or []):
        老 = 旧目.get(str(e.get("title")))
        if 老:
            e["id"] = 老.get("id") or e.get("id")
            e["created_at"] = 老.get("created_at") or e.get("created_at")
            e["updated_at"] = 老.get("updated_at") or e.get("updated_at")
            认回 += 1
        gid = str(e.get("group_id") or "")
        if gid in 组旧id:
            e["group_id"] = 组旧id[gid]
    M.ydump(新, spec)
    return 认回


def _出卡(到, out=print):
    工程 = os.path.join(到, 卡名)
    spec = os.path.join(工程, "source", "%s.spec.yaml" % 卡名)
    卡路径 = os.path.join(工程, "成品", "%s.card.json" % 卡名)
    os.makedirs(os.path.dirname(spec), exist_ok=True)
    os.makedirs(os.path.dirname(卡路径), exist_ok=True)

    # 重生成前先记下上一版的 id 与时间戳 —— 否则这一行写下去，旧身份就没了。
    旧 = None
    if os.path.exists(spec):
        try:
            旧 = M.yload(spec)
        except Exception:
            旧 = None

    M.ydump(_空卡(), spec)
    安静 = lambda *a, **k: None                     # noqa: E731  写内容时的过程日志不外泄

    for 名 in ("做法", "设计", "玩法", "界面"):
        C.add_group(spec, 名, out=安静)

    # 先放卡自己的头尾（常驻 / 必读），再放共用的方法论
    计划 = [
        ("你是制卡师", "", "常驻", [], "", 卡总则),
        ("访谈 · 一层一层问", "", "必读", [], "玩家刚开卡、或你要进入下一层时读这条。", 卡访谈),
        ("交付 · 你输出什么", "", "必读", [], "每定完一层、要交给玩家时读这条。", 卡交付),
        ("红线 · 会被静默吃掉的写法", "", "必读", [], "写任何条目之前过一遍。", 卡红线),
    ]
    for 标题, it in 方法论.items():
        计划.append((标题, it["组"], it["档位"], it.get("关键词") or [], it["提示"], it["正文"]))

    for 标题, 组, 档位, 关键词, 提示, 正文 in 计划:
        C.add_entry(spec, 标题, 分组=组, 模板=档位, 正文=正文,
                    关键词=关键词, 提示=提示, out=安静)

    if 旧 is not None:
        认回 = _认回身份(spec, 旧)
        out("  认回上一版身份 %d 条（id 与时间戳照旧，正文是新写的）" % 认回)
    pack.build(spec, 卡路径)
    # 顺手把手册与索引也出齐 —— 只重出卡、不管 文档/，那儿就会留着上一版的旧索引。
    for 建 in (manual.build_manual, manual.build_index):
        建(spec, out=安静)
    概 = validate.summarize(M.jload(卡路径))
    out("  条目 %d · 分组 %d · 变量 %d · 正则 %d"
        % (概["entries"], 概["groups"], 概["variables"], 概["regex"]))
    out("  成品卡 / 手册 / 索引都跟着这次内容重出了（不会留旧版）")
    return spec, 卡路径


# ============================================================ 出口

def 出(到=None, out=print):
    """出两份东西：给电脑 AI 的规程，与给 ElecKoi 的向导卡。"""
    到 = os.path.abspath(到 or "向导")
    os.makedirs(到, exist_ok=True)

    out("① 给电脑上的 AI 读的规程")
    规程路径 = os.path.join(到, 规程文件名)
    with open(规程路径, "w", encoding="utf-8", newline="\n") as f:
        f.write(规程正文())
    out("   %s（%d 字）" % (规程路径, len(规程正文())))

    技能路径 = os.path.join(到, 技能文件名)
    with open(技能路径, "w", encoding="utf-8", newline="\n") as f:
        f.write(技能前言 + 技能正文)
    out("   %s（门牌：工具在哪 + 规矩 + 指向规程；整个目录拷进 skills/ 就是技能）" % 技能路径)

    示例路径 = os.path.join(到, 示例文件名)
    with open(示例路径, "w", encoding="utf-8", newline="\n") as f:
        f.write(D.卡稿示例())
    out("   %s（一张能直接落成绿卡的完整卡稿 —— 照着改比对着空文件想快得多）" % 示例路径)

    out("② 给 ElecKoi 里的 AI 读的卡")
    spec, 卡路径 = _出卡(到, out=out)
    out("   %s" % spec)
    out("   %s" % 卡路径)

    out("")
    out("卡直接导入 ElecKoi 用；规程丢给 Claude Code / Codex 这类能跑命令的 AI 用。")
    return {"到": 到, "规程": 规程路径, "技能": 技能路径, "示例": 示例路径,
            "spec": spec, "卡": 卡路径}
